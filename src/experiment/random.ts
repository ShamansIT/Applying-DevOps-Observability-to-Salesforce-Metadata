// Seeded, deterministic randomness for the experiment. Every ordering, resample and shuffle uses an
// explicit recorded seed, so an execution schedule or a power estimate reproduces exactly. mulberry32
// is a small, well-distributed 32-bit generator - adequate for scheduling and bootstrap resampling,
// not for cryptography.

export function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// Fisher-Yates using an injected generator. Returns a new array; input is not mutated.
export function shuffle<T>(items: readonly T[], rand: () => number): T[] {
  const out = [...items];
  for (let i = out.length - 1; i > 0; i -= 1) {
    const j = Math.floor(rand() * (i + 1));
    const a = out[i] as T;
    const b = out[j] as T;
    out[i] = b;
    out[j] = a;
  }
  return out;
}
